#!/usr/bin/env python3
"""Write THIRD-PARTY-LICENSES.txt: the license of every crate that fringe_core and
fringe-cli link on Apple silicon macOS, with the license texts (and NOTICE files)
each crate ships. Run it after changing dependencies; scripts/release.sh fails when
the file is out of date.

usage: scripts/third-party-licenses.py [--check]
"""
import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-LICENSES.txt"
TARGET = "aarch64-apple-darwin"
TEXT_PREFIXES = ("license", "licence", "copying", "notice", "unlicense", "copyright")

MIT_TEMPLATE = """\
(This crate's package ships no license file; this is the standard MIT text for the
license it declares, with its authors as listed in its Cargo.toml.)

MIT License

Copyright (c) {holders}

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE."""


def declared_mit(pkg):
    """The standard MIT text for a crate that declares MIT (alone or as an option)
    but ships no license file; None otherwise."""
    options = [o.strip() for o in (pkg.get("license") or "").replace("/", " OR ").split(" OR ")]
    if "MIT" not in options:
        return None
    names = [a.split("<")[0].strip() for a in pkg.get("authors", [])]
    holders = ", ".join(n for n in names if n) or f"the {pkg['name']} authors"
    return MIT_TEMPLATE.format(holders=holders)


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", TARGET,
         "--manifest-path", str(ROOT / "Cargo.toml")],
        check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def shipped(meta):
    """Packages in the normal-dependency tree as features resolve it (what is linked
    or, for proc macros, generates linked code). `cargo metadata`'s resolve graph
    also keeps optional dependencies no feature turns on, so the set comes from
    `cargo tree`; build scripts and dev-dependencies don't ship."""
    out = subprocess.run(
        ["cargo", "tree", "--locked", "-e", "normal", "--target", TARGET, "--prefix", "none",
         "--format", "{p}", "--manifest-path", str(ROOT / "Cargo.toml")],
        check=True, capture_output=True, text=True).stdout
    used = set()
    for line in out.splitlines():
        name, version = line.split()[:2]
        used.add((name, version.lstrip("v")))
    root = meta["resolve"]["root"]
    return sorted((p for p in meta["packages"] if (p["name"], p["version"]) in used and p["id"] != root),
                  key=lambda p: (p["name"], p["version"]))


def license_files(pkg):
    folder = pathlib.Path(pkg["manifest_path"]).parent
    files = []
    if pkg.get("license_file"):
        files.append(folder / pkg["license_file"])
    for f in sorted(folder.iterdir()):
        if f.is_file() and f.name.lower().startswith(TEXT_PREFIXES) and f not in files:
            files.append(f)
    return files


def render():
    pkgs = shipped(metadata())
    lines = [
        "Third-party software in Fringe",
        "",
        "Fringe (the app and fringe-cli) is licensed under MIT OR Apache-2.0; see",
        "LICENSE-MIT and LICENSE-APACHE. It statically links the Rust crates below.",
        "Each is listed with its license as published, followed by the license texts",
        "and notices the crates ship. Where a crate offers a choice of licenses,",
        "Fringe uses it under MIT if that is one of them, otherwise under Apache-2.0.",
        "",
        "Generated by scripts/third-party-licenses.py from Cargo.lock; do not edit.",
        "",
        "",
        "Crates",
        "======",
        "",
    ]
    texts = {}  # digest -> (text, [crate names])
    missing = []
    for p in pkgs:
        lines.append(f"{p['name']} {p['version']}  ({p.get('license') or 'no license field'})"
                     + (f"  {p['repository']}" if p.get("repository") else ""))
        found = [(f.name, f.read_text(encoding="utf-8", errors="replace").strip()) for f in license_files(p)]
        # A crate used under MIT needs its MIT notice even when the files it ships
        # cover only other things (faer ships the licenses of code it ported).
        fallback = declared_mit(p)
        if fallback and not any("Permission is hereby granted" in text for _, text in found):
            found.append(("declared MIT", fallback))
        if not found:
            missing.append(f"{p['name']} {p['version']}")
            continue
        for name, text in found:
            digest = hashlib.sha256(text.encode()).hexdigest()
            texts.setdefault(digest, (text, []))[1].append(f"{p['name']} {p['version']} ({name})")
    lines += ["", "", "License texts and notices", "=========================", ""]
    for text, owners in texts.values():
        lines.append("-" * 78)
        lines.append("Used by: " + ", ".join(owners))
        lines.append("-" * 78)
        lines.append("")
        lines.append(text)
        lines.append("")
    return "\n".join(lines) + "\n", missing


def main():
    text, missing = render()
    if missing:
        sys.exit("error: no license file in: " + ", ".join(missing))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"error: {OUT.name} is out of date; run scripts/third-party-licenses.py")
        return
    OUT.write_text(text)
    print(OUT)


if __name__ == "__main__":
    main()
